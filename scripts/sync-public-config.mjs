import { readFileSync, mkdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const webSource = resolve(process.argv[2] ?? resolve(root, "../gistpad.dev/src/shared/supabase.ts"));
const source = readFileSync(webSource, "utf8");
const key = source.match(/const SUPABASE_PUBLISHABLE_KEY\s*=\s*"([^"]+)"/)?.[1];
if (!key) throw new Error("The web source has no SUPABASE_PUBLISHABLE_KEY literal.");
if (!key.startsWith("sb_publishable_")) {
  const claims = JSON.parse(Buffer.from(key.split(".")[1] ?? "", "base64url").toString("utf8"));
  if (claims.role !== "anon") throw new Error("Only a public publishable/anon key may enter app configuration.");
}
if (!/^[A-Za-z0-9_.-]+$/.test(key)) throw new Error("The public key contains unexpected xcconfig characters.");
mkdirSync(resolve(root, "Configuration"), { recursive: true });
writeFileSync(
  resolve(root, "Configuration/Public.xcconfig"),
  "// Generated by scripts/sync-public-config.mjs. This publishable key is not a secret.\n" +
    `SUPABASE_PUBLISHABLE_KEY = ${key}\n`,
);
console.log("Updated Configuration/Public.xcconfig with the verified public Supabase key.");
